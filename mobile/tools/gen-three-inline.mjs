#!/usr/bin/env node
// Build the offline 3D runtime for the digital twin (runs on postinstall; outputs are generated + gitignored):
//  • three.js + the add-ons the twin uses, bundled by esbuild into ONE self-contained ES module (add-ons import each
//    other by relative path, which can't resolve from the Blob URL the WebView loads it from).
//  • the anatomy model is NOT embedded — the backend serves it (/static/telomy_anatomy.glb), keeping the bundle small.
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url).pathname;
const entry = `
export * from 'three';
export { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';
export { OrbitControls } from 'three/examples/jsm/controls/OrbitControls.js';
export { RoomEnvironment } from 'three/examples/jsm/environments/RoomEnvironment.js';
export { EffectComposer } from 'three/examples/jsm/postprocessing/EffectComposer.js';
export { RenderPass } from 'three/examples/jsm/postprocessing/RenderPass.js';
export { UnrealBloomPass } from 'three/examples/jsm/postprocessing/UnrealBloomPass.js';
export { OutputPass } from 'three/examples/jsm/postprocessing/OutputPass.js';
`;
const r = await build({ stdin: { contents: entry, resolveDir: root, loader: 'js' }, bundle: true, format: 'esm', minify: true, write: false, target: 'safari16', logLevel: 'silent' });
const src = r.outputFiles[0].text;
const ver = JSON.parse(readFileSync(root + 'node_modules/three/package.json', 'utf8')).version;
writeFileSync(root + 'src/twin3d/threeSource.generated.ts', `// GENERATED by tools/gen-three-inline.mjs — do not edit. three.js ${ver} + add-ons (MIT)\nexport const THREE_SRC: string = ${JSON.stringify(src)};\n`);

console.log(`three ${ver} + add-ons → ${(src.length / 1024).toFixed(0)} KB`);

// Thinking orb (Sinc's "thinking" indicator): vendored engine + canvas driver → one IIFE string for a WebView.
const orb = await build({ entryPoints: [root + 'tools/orb-driver.ts'], bundle: true, format: 'iife', minify: true, write: false, target: 'safari16', logLevel: 'silent' });
writeFileSync(root + 'src/sinc/orbSource.generated.ts', `// GENERATED — thinking-orbs engine, MIT © 2026 Jakub Antalik (vendor/thinking-orbs/LICENSE)\nexport const ORB_SRC: string = ${JSON.stringify(orb.outputFiles[0].text)};\n`);
console.log(`thinking orb → ${(orb.outputFiles[0].text.length / 1024).toFixed(0)} KB`);
